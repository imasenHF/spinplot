import assert from 'node:assert/strict';
import {positiveAxisDomain,axisCoordinate,axisValue,scaledTicks} from './axis-scale.js';
const near=(v,target)=>assert.ok(Math.abs(v-target)<1e-10,target+' != '+v);
const values=[-2,0,.1,10];
assert.deepEqual(positiveAxisDomain(values,-3,12,'log'),[.1,12]);
assert.deepEqual(positiveAxisDomain(values,-3,12,'linear'),[-3,12]);
assert.deepEqual(positiveAxisDomain(values,.2,5,'log',{explicitMin:true,explicitMax:true}),[.2,5]);
assert.throws(()=>positiveAxisDomain(values,0,100,'log',{explicitMin:true}),/minimum must be positive/);
assert.throws(()=>positiveAxisDomain([-1,0],-3,3,'log'),/positive data/);
assert.throws(()=>positiveAxisDomain(values,5,1,'log',{explicitMin:true,explicitMax:true}),/increasing/);
const bipolar=positiveAxisDomain([-100,0,10],-120,12,'log',{signed:true});
assert.deepEqual(bipolar,[-120,12]);
const u=axisCoordinate(-10,-100,100,'log');
assert.ok(Number.isFinite(u) && u<.5);
near(axisValue(u,-100,100,'log'),-10);
near(axisCoordinate(0,-100,100,'log'),.5);
near(axisCoordinate(10,-100,100,'scientific'),.55);
const constant=positiveAxisDomain([10,10],10,10,'log');
assert.ok(constant[0]>0 && constant[1]>constant[0]);
near(axisCoordinate(10,1,100,'log'),.5);
near(axisValue(.5,1,100,'log'),10);
assert.ok(Number.isNaN(axisCoordinate(0,1,100,'log')));
assert.ok(Number.isNaN(axisCoordinate(-4,1,100,'log')));
near(axisCoordinate(0,-10,10,'linear'),.5);
scaledTicks(1,1e4,'log').forEach((value,i)=>near(value,10**i));
console.log('Logarithmic main/secondary axis regression PASS');
